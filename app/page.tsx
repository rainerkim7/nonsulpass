// 메인 페이지 라우팅 컨트롤러
export default function Page() {
  const [view, setView] = useState<'home' | 'hongik' | 'exam' | 'report'>('home')
  const [selectedUniv, setSelectedUniv] = useState<string>('홍익대학교')
  const [selectedExamId, setSelectedExamId] = useState<string>('hongik-2026-humanities-real')
  const [initialQuestion, setInitialQuestion] = useState<'q1' | 'q2'>('q1')

  // Gemini AI 실시간 채점 결과 데이터 상태
  const [gradingReport, setGradingReport] = useState<GradingReportData | null>(null)

  // 채점 리포트 화면 이동 처리 핸들러 (API 채점 결과가 전달되면 상태에 저장)
  const handleNavigateToReport = (report?: GradingReportData) => {
    if (report) {
      setGradingReport(report)
    }
    setView('report')
  }

  // 대학 선택 처리 핸들러
  const handleSelectUniv = (univId: string, univName: string) => {
    setSelectedUniv(univName)
    if (univId === 'hongik') {
      setView('hongik')
    } else {
      setSelectedExamId('hongik-2026-humanities-real')
      setView('exam')
    }
  }

  // 시험 모드로 진입하는 핸들러
  const handleStartExam = (univName?: string, examId?: string, questionId?: 'q1' | 'q2') => {
    if (univName) {
      setSelectedUniv(univName)
    }
    if (examId) {
      setSelectedExamId(examId)
    }
    if (questionId) {
      setInitialQuestion(questionId)
    }
    setView('exam')
  }

  return view === 'home' ? (
    <HomePage
      onExam={handleStartExam}
      onReport={() => setView('report')}
      onSelectUniv={handleSelectUniv}
    />
  ) : view === 'hongik' ? (
    <HongikPage
      onBack={() => setView('home')}
      onStartExam={handleStartExam}
    />
  ) : view === 'exam' ? (
    <ExamWorkspace
      selectedUniv={selectedUniv}
      selectedExamId={selectedExamId}
      initialQuestion={initialQuestion}
      onReport={handleNavigateToReport}
      onBack={() => setView('hongik')}
      onHome={() => setView('home')}
    />
  ) : (
    <ReportPage
      onExam={() => setView('exam')}
      reportData={gradingReport}
      onHome={() => setView('home')}
    />
  )
}
